//! The gem around the extension: `lib/`, `extconf.rb`, and the gemspec.

use askama::Template;

use crate::{
    core::{GeneratedFile, Result},
    target::ruby::{
        name_style::extension_directory,
        syntax::{ConstantPath, Literal},
    },
};

use super::file;

#[derive(Template)]
#[template(path = "target/ruby/lib.rb", escape = "none")]
struct LibTemplate<'package> {
    module: &'package ConstantPath,
    extension_path: Literal,
}

#[derive(Template)]
#[template(path = "target/ruby/extconf.rb", escape = "none")]
struct ExtconfTemplate {
    extension: Literal,
    artifact: Literal,
    feature_arguments: Vec<Literal>,
    toolchain_arguments: Vec<Literal>,
}

#[derive(Template)]
#[template(path = "target/ruby/gem.gemspec", escape = "none")]
struct GemspecTemplate {
    gem: Literal,
    version: Literal,
    summary: Literal,
    extconf: Literal,
    extension_files: Vec<Literal>,
}

/// Names that the package files share.
pub struct Package<'package> {
    pub gem: &'package str,
    pub version: &'package str,
    pub stem: &'package str,
    pub module: &'package ConstantPath,
    pub artifact: &'package str,
    pub crate_name: &'package str,
    pub feature_arguments: &'package [String],
    pub toolchain: Option<&'package str>,
}

impl Package<'_> {
    /// Renders the Ruby entry file, the build script, and the gemspec.
    pub fn render(&self) -> Result<Vec<GeneratedFile>> {
        let extension_dir = extension_directory(self.gem);
        Ok(vec![
            file(
                format!("lib/{}.rb", self.stem),
                LibTemplate {
                    module: self.module,
                    extension_path: Literal::string(&format!("{0}/{0}", self.stem)),
                }
                .render()?,
            )?,
            file(
                format!("{extension_dir}/extconf.rb"),
                ExtconfTemplate {
                    extension: Literal::string(self.stem),
                    artifact: Literal::string(self.artifact),
                    feature_arguments: self
                        .feature_arguments
                        .iter()
                        .map(|argument| Literal::string(argument))
                        .collect(),
                    toolchain_arguments: self.toolchain.map(Literal::string).into_iter().collect(),
                }
                .render()?,
            )?,
            file(
                format!("{}.gemspec", self.gem),
                GemspecTemplate {
                    gem: Literal::string(self.gem),
                    version: Literal::string(self.version),
                    summary: Literal::string(&format!(
                        "Ruby bindings for {}, generated by BoltFFI",
                        self.crate_name
                    )),
                    extconf: Literal::string(&format!("{extension_dir}/extconf.rb")),
                    // Only the sources: a local `make` leaves build output beside them.
                    extension_files: vec![
                        Literal::string(&format!("{extension_dir}/*.{{c,h,rb}}")),
                        Literal::string(&format!("{extension_dir}/crate/**/*")),
                    ],
                }
                .render()?,
            )?,
        ])
    }
}
